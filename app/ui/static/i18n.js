/* Inference Hub i18n — Turkce kaynak metin anahtardir, EN sozlugu cevirir.
   Kullanim:
     t("Pull baslatildi")                          -> dile gore metin
     t("{n} model bulundu", { n: 12 })             -> parametreli
     HTML: <span data-i18n>Sohbet</span>           -> textContent cevrilir
           <input data-i18n-attrs="placeholder" placeholder="Kullanici adi" />
   Dil tercihi localStorage("hub_lang"): "tr" (varsayilan) | "en". */
(function () {
  const stored = localStorage.getItem("hub_lang");
  const lang = stored === "en" ? "en" : "tr";
  window.hubLang = lang;
  document.documentElement.setAttribute("lang", lang);

  window.I18N_EN = window.I18N_EN || {};

  window.t = function (text, params) {
    let out = text;
    if (window.hubLang === "en") {
      out = window.I18N_EN[text] !== undefined ? window.I18N_EN[text] : text;
    }
    if (params) {
      out = out.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? params[k] : m));
    } else if (window.hubLang === "tr") {
      out = out.replace(/\{(\w+)\}/g, "");
    }
    return out;
  };

  window.applyTranslations = function (root) {
    if (window.hubLang !== "en") return;
    const scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.textContent.trim();
      if (key && window.I18N_EN[key] !== undefined) el.textContent = window.I18N_EN[key];
    });
    scope.querySelectorAll("[data-i18n-attrs]").forEach((el) => {
      for (const attr of el.dataset.i18nAttrs.split(",")) {
        const name = attr.trim();
        const val = el.getAttribute(name);
        if (val && window.I18N_EN[val.trim()] !== undefined) {
          el.setAttribute(name, window.I18N_EN[val.trim()]);
        }
      }
    });
  };

  window.setHubLang = function (next) {
    localStorage.setItem("hub_lang", next === "en" ? "en" : "tr");
    location.reload();
  };

  document.addEventListener("DOMContentLoaded", () => {
    window.applyTranslations(document);
    const btn = document.getElementById("langToggle");
    if (btn) {
      const lbl = btn.querySelector(".lbl");
      if (lbl) lbl.textContent = lang === "en" ? "Language: EN" : "Dil: TR";
      btn.addEventListener("click", () => window.setHubLang(lang === "en" ? "tr" : "en"));
    }
  });
})();

